"""Predefined SLURM jobs."""

import shlex
from typing import TYPE_CHECKING, Literal, NamedTuple

if TYPE_CHECKING:
    from saspbft.types import Architecture, DatasetName, LogLevel, PrefixInit


class _Cli(NamedTuple):
    """Parameters for a single `uv run --no-sync cli ...` invocation."""

    command: Literal["fine-tune", "prompt-tune", "few-shot"]
    dataset: DatasetName
    arch: Architecture
    prefix_init: PrefixInit
    head_only: bool
    train_samples: int
    val_samples: int
    epochs: int
    batch_size: int
    experiment: str
    log_level: LogLevel
    seed: int


class _Job(NamedTuple):
    """SLURM job paramerts."""

    job_name: str
    time: str
    mem: str
    cpus: int
    gres: str
    models: tuple[str, ...]
    cli: _Cli


